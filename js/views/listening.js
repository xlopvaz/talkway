import { icon } from '../icons.js';
import { store } from '../store.js';
import { t, es } from '../i18n.js';
import { esc, pageHead, back, exercises, sayBtn, doneBtn } from '../ui.js';
import { LISTENING, LISTEN_TYPES } from '../data/listening.js';
import { ACCENTS, voicesFor, speakDialogue, stopSpeaking, ttsAvailable } from '../speech.js';

export function render([id]) {
  if (id) return detail(id);
  return {
    title: t('listening'),
    html: `<div class="view">${pageHead('Train your ear', t('listening'), 'Conversations, announcements, phone messages, interviews and talks in British, American, Australian, Irish and Canadian English. Replay at any speed.', 'Escucha distintos acentos y velocidades.')}
    <div class="row" style="margin-bottom:16px" id="accFilter"><span class="small muted">Accent:</span><button class="btn sm dark" data-acc="">All</button>${[...new Set(LISTENING.map((l) => l.accent))].map((a) => `<button class="btn sm" data-acc="${a}">${ACCENTS[a]}</button>`).join('')}</div>
    ${LISTEN_TYPES.map((type) => { const items = LISTENING.filter((l) => l.type === type); if (!items.length) return '';
      return `<section class="section" style="margin-top:20px"><h2>${type}</h2><div class="grid auto">${items.map((l) => `<a class="card click" href="#/listening/${l.id}" data-accent="${l.accent}">
        <div class="row between"><span class="ico blue">${icon(type.includes('Airport') ? 'plane' : type.includes('Phone') ? 'chat' : 'headphones')}</span><span class="row" style="gap:6px"><span class="tag">${l.level}</span><span class="tag blue">${ACCENTS[l.accent]}</span></span></div>
        <h3 style="margin-top:12px">${esc(l.title)}</h3><p class="small muted" style="margin:0">${esc(l.desc)}</p>${store.isDone(l.id) ? `<div class="tag mint" style="margin-top:8px">${icon('check')} ${t('done')}</div>` : ''}</a>`).join('')}</div></section>`; }).join('')}</div>`,
    mount(root) {
      root.querySelector('#accFilter').onclick = (e) => {
        const b = e.target.closest('[data-acc]'); if (!b) return;
        root.querySelectorAll('[data-acc]').forEach((x) => x.classList.toggle('dark', x === b));
        root.querySelectorAll('[data-accent]').forEach((c) => (c.style.display = !b.dataset.acc || c.dataset.accent === b.dataset.acc ? '' : 'none'));
        root.querySelectorAll('section').forEach((s) => (s.style.display = [...s.querySelectorAll('[data-accent]')].some((c) => c.style.display !== 'none') ? '' : 'none'));
      };
    },
  };
}

function detail(id) {
  const l = LISTENING.find((x) => x.id === id);
  if (!l) return { title: '404', html: '<div class="empty">Not found</div>' };
  store.visit(l.id, `Listening: ${l.title}`, `#/listening/${l.id}`);
  const hasVoice = voicesFor(l.accent).length > 0;
  let rate = 1, playing = false, plays = 0;
  const highlight = (txt) => l.expr.reduce((acc, x) => acc.replace(new RegExp(x.w.replace(/[.*+?^${}()|[\]\\…]/g, '\\$&'), 'i'), (m) => `<mark style="background:var(--amber-soft);color:inherit;border-radius:4px;padding:0 2px">${m}</mark>`), esc(txt));
  return {
    title: l.title,
    html: `<div class="view">${back('#/listening', t('listening'))}
    ${pageHead(`${l.type} · ${l.level} · ${ACCENTS[l.accent]} English`, esc(l.title), esc(l.desc))}
    <div class="player">
      <button class="btn" id="lPlay">${icon('play')} ${t('listen')}</button>
      <button class="btn sm ghost" id="lStop" style="background:transparent;color:inherit;border-color:transparent">${icon('stop')}</button>
      <div class="speeds" id="lSpeeds">${[0.6, 0.8, 1, 1.2].map((r) => `<button data-r="${r}" class="${r === 1 ? 'on' : ''}">${r}×</button>`).join('')}</div>
      <span class="small" id="lInfo" style="opacity:.75;margin-left:auto">${ttsAvailable() ? (hasVoice ? `${ACCENTS[l.accent]} voice` : `No ${ACCENTS[l.accent]} voice on this device — using a default English voice`) : 'Audio not supported in this browser'}</span>
    </div>
    <div class="callout small" style="margin-top:10px">Audio is generated by your device’s text-to-speech voices. Voice quality and accents depend on your device/browser (Chrome and Edge offer the most natural voices).</div>
    <div class="grid g2 section" style="align-items:start;margin-top:18px">
      <div class="stack">
        <div class="card"><h2>1 · Answer the questions</h2><p class="small muted">Listen first — no peeking at the transcript!</p>${exercises(l.q, { skill: 'listening' })}</div>
        <div class="card"><h2>2 · Complete the missing words</h2>${exercises(l.gaps.map((g) => ({ type: 'gap', ...g })), { skill: 'listening' })}</div>
      </div>
      <div class="stack">
        <details class="tx" id="lTx"><summary>3 · ${t('showTranscript')}</summary><div class="dialogue" style="margin-top:12px">${l.lines.map((x, i) => `<div class="line" data-li="${i}"><div class="avatar">${esc(x.s.slice(0, 2))}</div><div class="bubble"><span class="who">${esc(x.s)}</span>${highlight(x.t)}${sayBtn(x.t, l.accent)}</div></div>`).join('')}</div></details>
        <div class="card"><h2>4 · New expressions</h2><div class="vlist">${l.expr.map((x) => `<div class="vitem"><div style="flex:1"><b>${esc(x.w)}</b> ${sayBtn(x.w, l.accent)}<div class="small muted">${esc(x.d)}</div></div></div>`).join('')}</div></div>
        <div class="card tint-mint"><div class="row between"><div><b>5 · Listen again at a different speed</b><div class="small muted" id="lPlays">Plays: 0</div></div>${doneBtn(l.id, `Listening: ${l.title}`, `#/listening/${l.id}`, 'listening', 20)}</div></div>
      </div>
    </div></div>`,
    mount(root) {
      const playBtn = root.querySelector('#lPlay');
      const reset = () => { playing = false; playBtn.innerHTML = `${icon('play')} ${t('listen')}`; root.querySelectorAll('[data-li]').forEach((e) => (e.style.opacity = 1)); };
      playBtn.onclick = async () => {
        if (playing) { stopSpeaking(); reset(); return; }
        playing = true; plays++; root.querySelector('#lPlays').textContent = `Plays: ${plays}`;
        playBtn.innerHTML = `${icon('pause')} Stop`;
        if (plays === 1) store.award('listening', 3, true);
        await speakDialogue(l.lines.map((x) => ({ ...x, accent: l.accent })), { rate, accent: l.accent, cancelled: () => !playing,
          onLine: (i) => root.querySelectorAll('[data-li]').forEach((e, k) => (e.style.opacity = i < 0 || k === i ? 1 : 0.35)) });
        reset();
      };
      root.querySelector('#lStop').onclick = () => { stopSpeaking(); reset(); };
      root.querySelector('#lSpeeds').onclick = (e) => {
        const b = e.target.closest('[data-r]'); if (!b) return; rate = +b.dataset.r;
        root.querySelectorAll('#lSpeeds button').forEach((x) => x.classList.toggle('on', x === b));
      };
      return () => stopSpeaking();
    },
  };
}
